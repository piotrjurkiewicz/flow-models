def product_dict(**kwargs):
    keys = kwargs.keys()
    for instance in itertools.product(*kwargs.values()):
        yield dict(zip(keys, instance))

def test_convert():
    result = array.array('Q')
    flow_models.convert.convert([IN_FILES], result, in_format='binary', out_format='extend')
