    result = array.array('Q')
    flow_models.convert.convert([IN_FILES + '_4096'], result, in_format='binary', out_format='extend')
    assert len(result) == 4096 * 21
    assert hashlib.md5(result).hexdigest() == 'bdb1c629f04b58c8f0962884625c1825'

